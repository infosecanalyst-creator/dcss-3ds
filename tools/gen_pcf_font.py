#!/usr/bin/env python3
"""X11 misc-fixed PCF (public domain, full ISO10646) -> C header for lib3ds.

Usage: gen_pcf_font.py <font.pcf[.gz]> <out.h> <NAME> [ranges...]
Ranges are hex 'lo-hi'; default covers what crawl prints (Latin, Greek,
arrows, maths, box drawing, blocks, geometric shapes, misc symbols).
Output: NAME_W, NAME_H, NAME_ASCENT, NAME_N, sorted NAME_cp[] and
NAME_bits[][NAME_H] (row bitmaps, MSB = leftmost pixel)."""
import gzip, struct, sys

def load_pcf(path):
    data = gzip.open(path).read() if path.endswith(".gz") else open(path, "rb").read()
    assert data[:4] == b"\x01fcp"
    ntab = struct.unpack_from("<I", data, 4)[0]
    tabs = {}
    for i in range(ntab):
        t, fmt, size, off = struct.unpack_from("<IIII", data, 8 + i * 16)
        tabs[t] = (fmt, off)
    def hdr(t):
        fmt, off = tabs[t]
        fmt = struct.unpack_from("<I", data, off)[0]
        e = ">" if fmt & 4 else "<"
        return fmt, off + 4, e
    # metrics
    fmt, p, e = hdr(1 << 2)
    metrics = []
    if fmt & 0x100:
        n = struct.unpack_from(e + "H", data, p)[0]; p += 2
        for i in range(n):
            l, r, w, a, d = [b - 0x80 for b in data[p:p + 5]]; p += 5
            metrics.append((l, r, w, a, d))
    else:
        n = struct.unpack_from(e + "I", data, p)[0]; p += 4
        for i in range(n):
            l, r, w, a, d, _ = struct.unpack_from(e + "hhhhhH", data, p); p += 12
            metrics.append((l, r, w, a, d))
    # bitmaps
    fmt, p, e = hdr(1 << 3)
    n = struct.unpack_from(e + "I", data, p)[0]; p += 4
    offs = struct.unpack_from(e + "%dI" % n, data, p); p += 4 * n
    sizes = struct.unpack_from(e + "4I", data, p); p += 16
    bits = data[p:p + sizes[fmt & 3]]
    pad = 1 << (fmt & 3)
    msbbit = bool(fmt & 8)
    # encodings
    fmt, p, e = hdr(1 << 5)
    minb2, maxb2, minb1, maxb1, defc = struct.unpack_from(e + "5H", data, p); p += 10
    cols = maxb2 - minb2 + 1
    enc = {}
    for b1 in range(minb1, maxb1 + 1):
        for b2 in range(minb2, maxb2 + 1):
            idx = struct.unpack_from(e + "H", data, p)[0]; p += 2
            if idx != 0xFFFF:
                enc[(b1 << 8) | b2] = idx
    return metrics, offs, bits, pad, msbbit, enc

def main():
    path, out, name = sys.argv[1], sys.argv[2], sys.argv[3]
    ranges = sys.argv[4:] or ["20-7e", "a0-17f", "391-3c9", "2010-2027", "2030-205e", "20ac-20ac",
                               "2190-21ff", "2200-22ff", "2300-23ff", "2500-25ff", "2600-26ff", "2700-27bf"]
    metrics, offs, bits, pad, msbbit, enc = load_pcf(path)
    W = max(m[2] for m in metrics)
    asc = max(m[3] for m in metrics); desc = max(m[4] for m in metrics)
    H = asc + desc
    glyphs = []
    for rg in ranges:
        lo, hi = [int(x, 16) for x in rg.split("-")]
        for cp in range(lo, hi + 1):
            if cp not in enc: continue
            gi = enc[cp]; l, r, w, a, d = metrics[gi]
            gw = r - l; stride = ((gw + 7) // 8 + pad - 1) // pad * pad
            o = offs[gi]
            rows = [0] * H
            for y in range(a + d):
                row = bits[o + y * stride: o + (y + 1) * stride]
                for x in range(gw):
                    byte = row[x // 8]
                    on = (byte >> (7 - x % 8)) & 1 if msbbit else (byte >> (x % 8)) & 1
                    if on:
                        px = x + l; py = asc - a + y
                        if 0 <= px < W and 0 <= py < H:
                            rows[py] |= 1 << (W - 1 - px)
            glyphs.append((cp, rows))
    glyphs.sort()
    N = name.upper()
    typ = "uint8_t" if W <= 8 else "uint16_t"
    with open(out, "w") as f:
        f.write("// Generated by tools/gen_pcf_font.py from X11 misc-fixed (public domain). Do not edit.\n")
        f.write("#pragma once\n#include <stdint.h>\n")
        f.write("#define %s_W %d\n#define %s_H %d\n#define %s_ASCENT %d\n#define %s_N %d\n" % (N, W, N, H, N, asc, N, len(glyphs)))
        f.write("static const uint16_t %s_cp[%d] = {%s};\n" % (name, len(glyphs), ",".join(str(c) for c, _ in glyphs)))
        f.write("static const %s %s_bits[%d][%d] = {\n" % (typ, name, len(glyphs), H))
        for c, rows in glyphs:
            f.write("{%s},\n" % ",".join(str(r) for r in rows))
        f.write("};\n")
    print("%s: %dx%d, %d glyphs" % (out, W, H, len(glyphs)))

main()
